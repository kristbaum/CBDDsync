"""
unmatched_report.py

Collect everything the reconciliation reports say about the entities that are
still unmatched (rows of missing/missing_{people,buildings,paintings}.csv) into
one Markdown file, grouped by type, one block per entity, report excerpts in
chronological order. Entities no report mentions get a stub from the CSV row.

Run from the repository root:

    uv run python agentic-reconcile/scripts/unmatched_report.py [--out missing/unmatched_entities.md]
"""

import argparse
import csv
import re
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

TO_MATCH = Path("agentic-reconcile/to_match")
TYPES = {
    "people": ("People", ["gender", "gnd"]),
    "buildings": (
        "Buildings",
        ["verbaleDating", "addressState", "addressLocality", "addressStreet"],
    ),
    "paintings": (
        "Paintings",
        [
            "verbaleDating",
            "description_de",
            "location",
            "primaryIconography",
            "painter",
            "commissioner",
        ],
    ),
}
DECISIONS = ("Matched", "New items", "Uncertain", "No match")
UUID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")


@dataclass
class Excerpt:
    report: str
    category: str
    text: str


def reports() -> list[Path]:
    """All report files, oldest first (run names start with <type>_<date>)."""
    files = list(TO_MATCH.glob("*.md")) + list(TO_MATCH.glob("*/report.md"))

    def key(p: Path) -> tuple[str, str]:
        name = p.parent.name if p.name == "report.md" else p.stem
        date = re.search(r"\d{4}-\d{2}-\d{2}(_\d+)?", name)
        return (date.group(0) if date else "", name)

    return sorted(files, key=key)


def report_name(p: Path) -> str:
    return str(p.relative_to(TO_MATCH))


def index_reports() -> dict[str, list[Excerpt]]:
    """Map CbDD UUID → excerpts (### sections and top-level bullets)."""
    index: dict[str, list[Excerpt]] = defaultdict(list)
    own_id = re.compile(r"deckenmalerei\.eu/(" + UUID.pattern + ")")
    for path in reports():
        name = report_name(path)
        for category, block in blocks(path.read_text(encoding="utf-8")):
            if block.startswith("### "):
                # the entity's own ID is on the "CbDD: https://…/<uuid>" line
                if own := own_id.search(block):
                    index[own.group(1)].append(Excerpt(name, category, block))
            else:
                # bullet (No match, New items, Repairs, corrections, Notes)
                for uid in dict.fromkeys(UUID.findall(block)):
                    index[uid].append(Excerpt(name, category, block[2:]))
    return index


def blocks(text: str) -> list[tuple[str, str]]:
    """Split a report into (## category, block) pairs; a block is a ### section
    or a bullet line outside any ### section."""
    out: list[tuple[str, str]] = []
    category, section = "", []
    for line in [*text.splitlines(), "## "]:
        if line.startswith(("## ", "### ")) and section:
            out.append((category, "\n".join(section).strip()))
            section = []
        if line.startswith("## "):
            category = line[3:].strip()
        elif line.startswith("### ") or section:
            section.append(line)
        elif line.startswith("- "):
            out.append((category, line.strip()))
    return out


def demote(text: str) -> str:
    """Report ### headings become bold lines inside the entity block."""
    lines = text.splitlines()
    if lines and lines[0].startswith("### "):
        lines[0] = f"**{lines[0][4:]}**"
    return "\n".join(lines)


def render(out: Path) -> None:
    index = index_reports()
    parts = [
        "# Unmatched CbDD entities",
        "",
        (
            "Entities of `missing/missing_{people,buildings,paintings}.csv` that "
            "still have no Wikidata item with their deckenmalerei.eu ID (P10626), "
            "with everything the reconciliation runs in `agentic-reconcile/to_match/` "
            "say about them, oldest run first. Generated by "
            "`agentic-reconcile/scripts/unmatched_report.py`; do not edit by hand."
        ),
        "",
    ]
    summary, body = [], []
    for label, (title, fields) in TYPES.items():
        with open(f"missing/missing_{label}.csv", encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
        rows.sort(key=lambda r: r["appellation"].casefold())
        unreported = sum(1 for r in rows if r["ID"] not in index)
        summary.append(
            f"| {title} | {len(rows)} | {len(rows) - unreported} | {unreported} |"
        )
        body += [f"## {title} ({len(rows)})", ""]
        for row in rows:
            uid = row["ID"]
            body += [f"### {row['appellation'] or '(no name)'}", ""]
            facts = [f"[{uid}]({row['url']})"]
            facts += [f"{k}: {row[k]}" for k in fields if row.get(k)]
            body += [" · ".join(facts), ""]
            excerpts = index.get(uid)
            if not excerpts:
                body += ["*Not yet in any reconciliation report.*", ""]
                continue
            decisions = [e for e in excerpts if e.category.startswith(DECISIONS)]
            if decisions:
                last = decisions[-1]
                body += [f"Latest decision: **{last.category}** ({last.report})", ""]
            else:
                body += ["*No match decision yet, only the notes below.*", ""]
            for ex in excerpts:
                body += [
                    f"<details><summary>{ex.report} — {ex.category}</summary>",
                    "",
                    demote(ex.text),
                    "",
                    "</details>",
                    "",
                ]
    parts += [
        "| Type | Unmatched | In a report | Not yet reported |",
        "|---|---|---|---|",
        *summary,
        "",
        *body,
    ]
    out.write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {out}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--out", type=Path, default=Path("missing/unmatched_entities.md"))
    render(ap.parse_args().out)


if __name__ == "__main__":
    main()
